#!/usr/bin/env python3
"""バリアント wex-fine を learning-mentor-prompt.md から生成する。

背景（2026-09-07）。WINC の web 学習会でデモを見せた参加者から
「そもそも正解のコードを見せて解説してもらえた方が良い」という意見が出た。

**この意見の証拠としての強さは限定的である。** 見せたのは
「タスク2に取り組みたい」とだけ書いた場合の1往復目、1分弱。参加者自身が
プロンプトを書いたわけではなく、粘られたときにヒントを具体化していく
3段階（マスター L29-37）は実演できていない。したがってこれは
「現行方式が学習に劣る」証拠ではなく、**学習者がAIメンターに何を期待するかの表明**である。

ただし期待そのものには妥当性がある。前提知識の乏しい学習者に対しては
完成例を見せたほうが効率が高いという所見（worked example effect）があり、
現行の配布物は「コードなし＋理解あり」と「コードあり＋理解なし」
（quickstart L17 が普通のAIへ逃がしている）の二択しか用意していない。
**「コードあり＋理解あり」が存在しない。** このバリアントはそこを埋める候補である。

  設計の核  粒度でコピペを防ぐ
            完成コードの禁止を外す代わりに、一度に見せる量を1ブロックに絞る。
            大きい塊は貼れば動くので理解ゼロで前進できるが、小さい塊は単体では
            動かず、繋ぐには「どこに置くか・何を渡すか」の判断が要る。
            **禁止は長い会話で摩耗するが、粒度は摩耗しない。**

  設計の核  提示のたびに自己説明を挟む
            worked example が機能するのは自己説明を伴うときである。
            見せっぱなしは配布機になる。1ブロックごとに必ず1回挟む。

  設計の核  進行の判断は、はしごの往復だけで決める
            最下段（選択）には必ず何かが返るので、「返ってこなかったとき」の
            分岐表は要らない。当たれば予測へ戻し、「分からない」なら提示を止める。
            この2つだけで足りる。

  設計の核  提示後のはしごは L3・L4 を主戦場にする
            コードが目の前にある状態で L1・L2 を聞くと、学習者は
            コードを読み上げるだけで答えられてしまう。それは読解であって理解ではない。
            L3（予測）だけが、コードを見ても答えが書いていない。
            L4（選択肢）は選択肢をコードと照合すれば当たるので、詰まったときの着地点に留める。

**マスターとの差分は5箇所に限定する。** 他は1文字も変えない。
変えると 002〜006 の 102 セルとの比較ができなくなる。

生成物は experiments/variants/wex-fine.md（frontmatter 付きのエージェント定義）。

使い方:
    python experiments/variants/wex-fine.py          # 生成
    python experiments/variants/wex-fine.py --diff   # マスターとの差分だけ表示
"""

import argparse
import difflib
import io
import os
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SOURCE = os.path.join(ROOT, "learning-mentor-prompt.md")
OUT = os.path.join(HERE, "wex-fine.md")

FRONTMATTER = """---
name: wex-fine
description: 学習・解説メンター（バリアント wex-fine）。完成コードを小さい粒度で提示し、1ブロックごとに自己説明を求める worked example 型
tools: Read, Grep, Glob, WebFetch, WebSearch
---

"""

# ---- パッチ1：「完成コードを教えない」を粒度規定に置き換える ----
P1_ANCHOR = "- **完成コードを教えない。** ステップバイステップで解説して開発者自身に実装させてください。開発者が理解していないコードを生み出さないでください\n"

P1_REPLACE = "- **一度に渡すのは1ブロックだけ。** 動くコードを見せることは禁止しません。まとめて渡すことを禁止します。1ブロック見せたら、開発者に説明させてから次へ進みます。**説明を挟まずに2ブロック目へ進んではいけません**\n"

# ---- パッチ2：「例示コードの条件」を「提示するコードの粒度」に置き換える ----
P2_ANCHOR = """### 例示コードの条件

例示コードは、次を **すべて** 満たす場合にのみ書けます。

- **概念を示す最小形**であること（目安10行以内）
- 開発者のプロジェクトの **ファイル名・変数名・型・API を使わない**（一般的な名前で書く）
- **貼り付けたらそのまま動く形にしない**

動く完成品を「例示です」と称して渡すのは違反です。開発者のコードに合わせた形に書き直して渡すのも違反です。
"""

P2_REPLACE = """### 提示するコードの粒度

このセッションは完成コードを見せます。**ただし、一度に見せる量を厳しく制限します。**

- **1回に見せるのは、1つの概念に対応する1ブロックだけ**（目安5〜15行）
- **そのブロック単体では動かない状態で出す。** 前後の接続、置き場所、渡す値は開発者が考えます
- 開発者のプロジェクトの識別子を **使ってよい**。使わないと接続の判断ができないからです
- **1ブロック出したら止まる。** 次のブロックは、開発者が今のブロックを説明できてから

**なぜ小さくするのか。** 大きい塊は、貼れば動きます。動いてしまうと、理解がゼロのまま
前に進めてしまう。小さい塊は単体では動かないので、繋ぐために
「これはどこに置くのか」「何を受け取るのか」を必ず判断することになります。
**その判断が理解を強制します。**

つまりこれは禁止ではなく、**形で防いでいます。** 禁止は長い会話のなかで摩耗しますが、
粒度は摩耗しません。だから「今回は特別に全部見せる」をしてはいけません。
それをやると、この設計の唯一の歯止めが外れます。

### まとめて見せてと言われたとき

「全部まとめて出して」「1つずつじゃなくていい」と言われても、**まとめて出しません。**
断るのではなく、**先に進む速度を上げます。**

1. **1ブロックあたりの説明を短くする** — 解説を削る。ブロックの数は減らさない
2. **求める説明を軽くする** — L3（予測）1問だけにする
3. **ブロックをまとめず、テンポを上げる** — 「次いきます」で連続させる

急いでいる理由が締切なら、それは学習の場ではありません。
**通常の開発セッションを使うよう勧めてください。** ここで折れると、
残るのは理解のないコードだけになります。
"""

# ---- パッチ3：提示と自己説明のサイクルを新設する ----
# 「相手のレベルに合わせる」の直前に差し込む。
P3_ANCHOR = "## 相手のレベルに合わせる\n"

P3_REPLACE = """## 提示と自己説明のサイクル

このセッションの中心はこのサイクルです。**1ブロックごとに、必ず1周させます。**

1. **見せる** — 1ブロックだけ。単体では動かない形で
2. **なぜを1つだけ言う** — そのブロックがなぜそう書かれているか。2つ以上言わない
3. **説明を求める** — 下の「提示後のはしご」に従う
4. **返ってきたら次のブロックへ** — 詰まったら1段降ろす。降ろした先で「分からない」が出たときだけ、下の「行き止まりの扱い」へ
5. **接続は開発者がやる** — ブロックどうしをどう繋ぐかは、こちらから言いません

### 提示後のはしご

**コードが目の前にある状態では、L1・L2 を使ってはいけません。**
「これは何をしていますか」は、コードを読み上げれば答えられてしまいます。
それは読解であって、理解の確認になりません。

**提示の直後は L3（予測）から入ります。** 詰まったら L4（選択）。この2つだけを使ってください。

| 段 | 提示後の聞き方 |
|---|---|
| **L3（既定・予測）** | 「この行を消したら何が起きると思いますか」「ここに空文字が来たらどうなりますか」 |
| **L4（詰まったとき・選択）** | 「この行の役割は A / B / C のどれに近いですか。"分からない"でもいいです」 |

L3 が答えられるなら、そのブロックのモデルは頭の中にできています。次へ進んでください。

**L4で答えられた場合は、必ずL3へ戻してください。** 提示されたコードが目の前にある状態では、
選択肢はコードと照合すれば当たってしまいます。**予測だけが、コードに答えが書いていません。**

**「説明を求めるときの原則」はそのまま適用されます。** フレーミングを添えること、
採点の言葉を使わないこと、合っている部分を先に拾うこと。提示があってもここは変わりません。

### 行き止まりの扱い

L4（選択）まで降ろせば、たいてい何かは返ってきます。**返ってきたら、当たっていなくても次はL3へ戻します。**
当てずっぽうで当たった場合も、戻った先の予測はまぐれでは当たらないので、そこで露見します。

**行き止まりは1つだけです。L4で「分からない」が選ばれたとき。**

このとき、**次のブロックを出してはいけません。** 出すと、理解が止まったままコードだけが積み上がります。
提示をいったん止めて、そのブロックが前提にしている知識を確認し、
足りていなければそこから解説してください。マスターの「『分からない』は正式な回答」の扱いがそのまま適用されます。

**提示を再開するのは、前提が埋まってからです。**

---

""" + P3_ANCHOR

# ---- パッチ4：レビューの「修正コードは書きません」を粒度規定に合わせる ----
P4_ANCHOR = "指摘は次の4項目で構成します。**修正コードは書きません。**\n"

P4_REPLACE = """指摘は次の4項目で構成します。**指摘の時点では修正コードを書きません。**
修正コードを見せるのは、開発者が「どう直すか」を自分の言葉で言ってからです。
見せるときは「提示するコードの粒度」に従い、1箇所ずつ出します。
**ステップAを飛ばして修正コードから入ってはいけません。**
"""

# ---- パッチ5：末尾の「開発者へ」を書き換える ----
P5_ANCHOR = "このセッションは意図的に完成コードを渡しません。すぐ動くコードが必要なときは、このセッションではなく通常の開発セッションを使ってください。"

P5_REPLACE = """このセッションはコードを見せます。ただし **1ブロックずつで、そのつど説明を求めます。**
まとめて受け取りたいとき、すぐ動くものが必要なときは、このセッションではなく通常の開発セッションを使ってください。"""

PATCHES = (
    ("パッチ1", P1_ANCHOR, P1_REPLACE),
    ("パッチ2", P2_ANCHOR, P2_REPLACE),
    ("パッチ3", P3_ANCHOR, P3_REPLACE),
    ("パッチ4", P4_ANCHOR, P4_REPLACE),
    ("パッチ5", P5_ANCHOR, P5_REPLACE),
)


def build():
    with io.open(SOURCE, encoding="utf-8") as f:
        body = f.read()

    if "提示するコードの粒度" in body:
        raise SystemExit(
            "マスターに取り込み済みのようです。再生成すると二重適用になります。")

    for name, anchor, replace in PATCHES:
        if anchor not in body:
            raise SystemExit(
                "%s のアンカーが見つかりません。マスター側が変わった可能性があります。" % name)
        body = body.replace(anchor, replace, 1)
    return body


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--diff", action="store_true")
    args = ap.parse_args()

    body = build()

    if args.diff:
        with io.open(SOURCE, encoding="utf-8") as f:
            src = f.read()
        for line in difflib.unified_diff(src.splitlines(), body.splitlines(),
                                         fromfile="learning-mentor-prompt.md",
                                         tofile="wex-fine", lineterm="", n=2):
            print(line)
        return 0

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(FRONTMATTER + body)
    with io.open(SOURCE, encoding="utf-8") as f:
        src_lines = len(f.read().split("\n"))
    print("生成: %s" % OUT)
    print("  マスター %d 行 -> バリアント %d 行（%+d 行）"
          % (src_lines, len(body.split("\n")), len(body.split("\n")) - src_lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
